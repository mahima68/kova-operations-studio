import assert from 'node:assert/strict';
const base=process.env.KOVA_TEST_URL||'http://127.0.0.1:5173';
assert.ok(new URL(base).hostname==='127.0.0.1','Run this test only against local development.');
const anonymous=await fetch(base+'/api/workspace');assert.equal(anonymous.status,401);
const signIn=await fetch(base+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=signIn.headers.getSetCookie().map(v=>v.split(';')[0]).join('; ');assert.ok(cookie);
const headers={cookie,'Content-Type':'application/json',origin:base};
const read=async()=>{const r=await fetch(base+'/api/workspace',{headers});assert.equal(r.status,200);return r.json();};
const initial=await read();assert.equal(initial.state.variants.length,60);
const post=(action,revision,origin=base)=>fetch(base+'/api/workspace',{method:'POST',headers:{...headers,origin},body:JSON.stringify({action,revision})});
assert.equal((await post({type:'task',id:'TASK-1'},initial.revision,'https://other.example')).status,403);
assert.equal((await post({type:'unknown'},initial.revision)).status,400);
const responses=await Promise.all([post({type:'task',id:'TASK-1'},initial.revision),post({type:'task',id:'TASK-1'},initial.revision)]);
assert.deepEqual(responses.map(r=>r.status).sort(),[200,409]);
const after=await read();assert.equal(after.revision,initial.revision+1);
assert.notEqual(after.state.tasks[0].done,initial.state.tasks[0].done);
assert.equal((await post({type:'task',id:'TASK-1'},initial.revision)).status,409);
const restore=await post({type:'task',id:'TASK-1'},after.revision);assert.equal(restore.status,200);
console.log('API smoke checks passed: sign-in, saved data, rejected cross-origin write, action validation and concurrent revision conflict.');
